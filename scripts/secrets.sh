#!/usr/bin/env bash
# Manage Wander secrets with SOPS + age. See docs/SECRETS.md.
#
#   scripts/secrets.sh edit <name>   open secrets/<name>.enc.yaml in $EDITOR (creates it if new)
#   scripts/secrets.sh xcconfig      write App/Config/Signing.local.xcconfig from secrets/signing.enc.yaml
#   scripts/secrets.sh rekey         re-encrypt every secrets file after recipients in .sops.yaml change
#   scripts/secrets.sh check         run scripts/check-secrets.sh
#
# Decryption needs an age private key in $SOPS_AGE_KEY_FILE (or $SOPS_AGE_KEY).
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

die() { echo "secrets: $*" >&2; exit 1; }
need_sops() { command -v sops >/dev/null || die "sops not found (brew install sops age)"; }

secret_path() {
  local name="${1:?usage: scripts/secrets.sh edit <name>}"
  name="${name#secrets/}"; name="${name%.enc.yaml}"
  [[ "$name" =~ ^[a-z0-9][a-z0-9_-]*$ ]] || die "name must be lowercase letters, digits, - or _"
  echo "secrets/$name.enc.yaml"
}

cmd_edit() {
  need_sops
  local f; f="$(secret_path "${1:-}")"
  # `sops edit` on a missing file opens a template and encrypts it on save.
  sops edit "$f"
}

cmd_xcconfig() {
  need_sops
  local src=secrets/signing.enc.yaml out=App/Config/Signing.local.xcconfig team
  [[ -f "$src" ]] || die "$src missing"
  team="$(sops decrypt --extract '["DEVELOPMENT_TEAM"]' "$src")"
  [[ "$team" =~ ^[A-Z0-9]{10}$ ]] || die "DEVELOPMENT_TEAM in $src is not a 10-character team ID"
  umask 077
  printf '// Generated by scripts/secrets.sh from %s. Do not commit (gitignored).\nDEVELOPMENT_TEAM = %s\n' "$src" "$team" > "$out"
  echo "wrote $out"
}

cmd_rekey() {
  need_sops
  local f found=0
  for f in secrets/*.enc.yaml secrets/*.enc.json secrets/*.enc.env; do
    [[ -e "$f" ]] || continue
    found=1
    sops updatekeys --yes "$f"
  done
  (( found )) || echo "no secrets files to rekey"
}

case "${1:-}" in
  edit)     shift; cmd_edit "$@" ;;
  xcconfig) cmd_xcconfig ;;
  rekey)    cmd_rekey ;;
  check)    exec scripts/check-secrets.sh ;;
  *)        sed -n '2,9p' "$0" | sed 's/^# \{0,1\}//'; exit 2 ;;
esac
